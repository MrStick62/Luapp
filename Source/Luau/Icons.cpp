void Icons::LoadGlobal(lua_State* LuauState)
{
   lua_createtable(LuauState, 0, std::size(IconsList));

   for (auto Icon : IconsList)
   {
      lua_pushstring(LuauState, Icon.second);
      lua_setfield(LuauState, -2, Icon.first);
   }

   lua_setglobal(LuauState, "Icons");
}

